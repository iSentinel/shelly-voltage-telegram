"""Ensure a candidate supervisor cannot silently add a second boot owner."""

from __future__ import annotations

import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UNIT = ROOT / "deploy/shelly-voltage-supervised.candidate.unit"


class SupervisedUnitCutoverTests(unittest.TestCase):
    """Verify the reviewed, uninstalled systemd cutover blueprint."""

    def setUp(self) -> None:
        """Read the tracked candidate unit without invoking systemd."""
        self.content = UNIT.read_text(encoding="utf-8")

    def test_candidate_not_directly_installable(self) -> None:
        """Keep the blueprint separate from installable service units."""
        self.assertEqual(UNIT.suffix, ".unit")

    def test_rejects_parallel_legacy_owner(self) -> None:
        """Declare a conflict with the legacy Docker Compose owner."""
        self.assertIn(
            "Conflicts=shelly-voltage-compose.service\n", self.content
        )

    def test_create_before_start_and_no_legacy_recovery(self) -> None:
        """The supervisor owns startup, never old automatic DB recovery."""
        self.assertIn("start-compose.sh --create-only", self.content)
        self.assertIn("scripts/supervised-container.py", self.content)
        self.assertNotIn("apply-update.sh --recover", self.content)

    def test_protected_fence_and_source_receipt_pair(self) -> None:
        """Require the same fence and pinned signed version identity."""
        self.assertIn(
            "--fence-dir /var/lib/shelly-voltage-fence", self.content
        )
        self.assertIn(
            "--receipt /var/lib/shelly-voltage-updater/deployed.json",
            self.content,
        )
        self.assertIn(
            "--source-version /opt/shelly-voltage/RELEASE_VERSION",
            self.content,
        )

    def test_sole_owner_requires_paired_signed_release_receipt(self) -> None:
        """Never start the production candidate on digest-only metadata."""
        self.assertIn("--require-pair-receipt", self.content)
        self.assertIn(
            "--source-archive-dir "
            "/var/lib/shelly-voltage-updater/signed-source",
            self.content,
        )
        self.assertNotIn("apply-update.sh --recover", self.content)

    def test_candidate_has_no_reload_competing_writer(self) -> None:
        """No legacy Compose restart may be hidden in a reload hook."""
        self.assertNotIn("ExecReload=", self.content)
        self.assertNotIn("RemainAfterExit=yes", self.content)
        self.assertIn("\nType=simple\n", self.content)

    def test_candidate_has_one_only_supervisor_start(self) -> None:
        """The sole launch command is the guarded Python supervisor."""
        directives = [
            line
            for line in self.content.splitlines()
            if line.startswith("ExecStart=")
        ]
        self.assertEqual(len(directives), 1)
        self.assertIn("scripts/supervised-container.py", directives[0])
        self.assertNotIn("start-compose.sh", directives[0])
        self.assertEqual(self.content.count("ExecStartPre="), 2)
        self.assertIn("start-compose.sh --create-only", self.content)

    def test_candidate_does_not_enable_parallel_legacy_recovery(self) -> None:
        """Conflicts are mandatory for retiring the live oneshot owner."""
        self.assertIn(
            "Conflicts=shelly-voltage-compose.service\n", self.content
        )
        self.assertNotIn("scripts/apply-update.sh", self.content)
        self.assertNotIn("docker compose up", self.content)

    def test_old_unit_not_modified(self) -> None:
        """No production service file may be generated by this blueprint."""
        self.assertNotEqual(UNIT.name, "shelly-voltage-compose.service")


if __name__ == "__main__":
    unittest.main()
